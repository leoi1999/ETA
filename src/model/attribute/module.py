import os
import pickle

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

from ..compatibility import install_numpy_pickle_compat
from ..embedding_cache import load_or_create_embedding_cache

MODALITY_NAME = "Attribute"


def _load_attribute_feature_table(path):
    install_numpy_pickle_compat()
    with open(path, "rb") as handle:
        data = pickle.load(handle)

    precomputed_score_matrix = None
    if "precomputed_score_matrix" in data:
        precomputed_score_matrix = np.asarray(
            data["precomputed_score_matrix"],
            dtype=np.float32,
        )

    entity_embeddings = data.get("entity_embeddings")
    entity_embedding_validity = data.get("entity_embedding_validity")
    if not entity_embeddings and precomputed_score_matrix is None:
        raise RuntimeError(
            "No entity embeddings or precomputed score matrix found in {}".format(path)
        )

    if entity_embeddings:
        max_entity_id = max(int(entity_id) for entity_id in entity_embeddings)
        sample_embedding = next(iter(entity_embeddings.values()))
        embedding_dim = int(np.asarray(sample_embedding).reshape(-1).shape[0])
        table = np.zeros((max_entity_id + 1, embedding_dim), dtype=np.float32)
        mask = np.zeros((max_entity_id + 1,), dtype=np.bool_)

        for entity_id, embedding in entity_embeddings.items():
            entity_id = int(entity_id)
            table[entity_id] = np.asarray(embedding, dtype=np.float32).reshape(-1)
            if entity_embedding_validity is None:
                mask[entity_id] = True
            else:
                mask[entity_id] = bool(
                    entity_embedding_validity.get(
                        entity_id,
                        entity_embedding_validity.get(str(entity_id), False),
                    )
                )
    else:
        table = np.zeros((1, 1), dtype=np.float32)
        mask = np.zeros((1,), dtype=np.bool_)

    return (
        torch.as_tensor(table, dtype=torch.float32),
        torch.as_tensor(mask, dtype=torch.bool),
        precomputed_score_matrix,
        data.get("metadata", {}),
    )


class AttributeModalityModule(nn.Module):
    """Paper-primary BERT attribute encoder."""

    def __init__(self, args, dataset_state):
        super().__init__()
        self.module_name = "attribute"
        self.modality_name = MODALITY_NAME
        self.temperature = args.attribute_temperature

        embedding_path = self._resolve_embedding_path(args, dataset_state)
        self.attribute_input_path = embedding_path

        (
            feature_table,
            feature_mask,
            precomputed_score_matrix,
            metadata,
        ) = load_or_create_embedding_cache(
            embedding_path,
            getattr(args, "embedding_cache_dir", None),
            "attribute",
            _load_attribute_feature_table,
        )
        self.attribute_metadata = metadata
        self.register_buffer("attribute_features", feature_table)
        self.register_buffer("attribute_feature_mask", feature_mask)
        self.use_projector = bool(args.attribute_use_projector)
        if precomputed_score_matrix is not None:
            if precomputed_score_matrix.ndim != 2:
                raise RuntimeError("Precomputed attribute score matrix must be 2D.")
            if precomputed_score_matrix.shape != (
                dataset_state.dev_pairs.shape[0],
                dataset_state.dev_pairs.shape[0],
            ):
                raise RuntimeError(
                    (
                        "Precomputed attribute score matrix shape {} does not "
                        "match dev pair count {}."
                    ).format(
                        precomputed_score_matrix.shape,
                        dataset_state.dev_pairs.shape[0],
                    )
                )
            score_description = str(metadata.get("runtime_score", "")).lower()
            if (
                "shifted cosine" in score_description
                or "(cosine + 1)" in score_description
            ):
                # Accept score files generated by older versions while exposing
                # raw cosine scores to the paper-defined fusion gate.
                precomputed_score_matrix = 2.0 * precomputed_score_matrix - 1.0
            precomputed_score_matrix = np.clip(precomputed_score_matrix, -1.0, 1.0)
            precomputed_score_tensor = torch.as_tensor(
                precomputed_score_matrix,
                dtype=torch.float32,
            )
        else:
            precomputed_score_tensor = torch.empty(0, dtype=torch.float32)
        self.register_buffer("precomputed_score_tensor", precomputed_score_tensor)
        self._frozen_entity_cache = None
        self.register_buffer(
            "eval_source_entity_ids",
            dataset_state.dev_pairs[:, 0].long().clone(),
        )
        self.register_buffer(
            "eval_target_entity_ids",
            dataset_state.dev_pairs[:, 1].long().clone(),
        )

        if self.uses_precomputed_score() or not self.use_projector:
            self.projector = nn.Identity()
        else:
            input_dim = int(self.attribute_features.shape[1])
            self.projector = nn.Sequential(
                nn.LayerNorm(input_dim),
                nn.Linear(input_dim, args.attribute_hidden_dim),
                nn.ReLU(),
                nn.Dropout(args.attribute_dropout),
                nn.Linear(args.attribute_hidden_dim, args.attribute_projection_dim),
            )

    @staticmethod
    def _resolve_embedding_path(args, dataset_state):
        if os.path.isabs(args.attribute_embedding_path):
            return args.attribute_embedding_path
        return os.path.join(
            args.data_root,
            dataset_state.dataset_name,
            args.attribute_embedding_path,
        )

    def supports_training(self):
        return self.use_projector and not self.uses_precomputed_score()

    def supports_decision_fusion_training(self):
        """Whether arbitrary supervised entity pairs can be scored safely."""
        return not self.uses_precomputed_score()

    def uses_precomputed_score(self):
        return self.precomputed_score_tensor.numel() > 0

    def _valid_entity_mask(self, entity_ids):
        if not isinstance(entity_ids, torch.Tensor):
            entity_ids = torch.as_tensor(entity_ids, dtype=torch.long)
        entity_ids = entity_ids.to(self.attribute_features.device).long()
        in_range = entity_ids < self.attribute_features.shape[0]
        valid = torch.zeros_like(in_range, dtype=torch.bool)
        if torch.any(in_range):
            valid[in_range] = self.attribute_feature_mask[entity_ids[in_range]]
        return valid

    def _lookup_attribute_features(self, entity_ids):
        if not isinstance(entity_ids, torch.Tensor):
            entity_ids = torch.as_tensor(entity_ids, dtype=torch.long)
        entity_ids = entity_ids.to(self.attribute_features.device).long()
        attribute_features = torch.zeros(
            entity_ids.shape[0],
            self.attribute_features.shape[1],
            dtype=self.attribute_features.dtype,
            device=self.attribute_features.device,
        )
        valid = self._valid_entity_mask(entity_ids)
        if torch.any(valid):
            attribute_features[valid] = self.attribute_features[entity_ids[valid]]
        return attribute_features, valid

    @torch.inference_mode()
    def prepare_frozen_similarity_cache(self, dataset_state=None):
        del dataset_state
        if self.uses_precomputed_score():
            return 0
        entity_ids = torch.arange(
            self.attribute_features.shape[0],
            dtype=torch.long,
            device=self.attribute_features.device,
        )
        projected, valid = self.encode_entity_ids(
            entity_ids,
            return_validity=True,
        )
        self._frozen_entity_cache = (projected.detach(), valid.detach())
        return sum(
            value.numel() * value.element_size()
            for value in self._frozen_entity_cache
        )

    def clear_frozen_similarity_cache(self):
        self._frozen_entity_cache = None

    def _lookup_frozen_entity_cache(self, entity_ids):
        if self._frozen_entity_cache is None:
            return None
        if not isinstance(entity_ids, torch.Tensor):
            entity_ids = torch.as_tensor(entity_ids, dtype=torch.long)
        cached_embeddings, cached_validity = self._frozen_entity_cache
        entity_ids = entity_ids.to(cached_embeddings.device).long()
        embeddings = torch.zeros(
            entity_ids.shape[0],
            cached_embeddings.shape[1],
            dtype=cached_embeddings.dtype,
            device=cached_embeddings.device,
        )
        valid = torch.zeros_like(entity_ids, dtype=torch.bool)
        in_range = (entity_ids >= 0) & (entity_ids < cached_embeddings.shape[0])
        if torch.any(in_range):
            selected_ids = entity_ids[in_range]
            embeddings[in_range] = cached_embeddings[selected_ids]
            valid[in_range] = cached_validity[selected_ids]
        return embeddings, valid

    def encode_entity_ids(self, entity_ids, return_validity=False):
        cached = self._lookup_frozen_entity_cache(entity_ids)
        if cached is None:
            attribute_features, valid = self._lookup_attribute_features(entity_ids)
            projected = self.projector(attribute_features)
            projected = F.normalize(projected, dim=-1)
            projected = projected * valid.unsqueeze(-1).to(projected.dtype)
        else:
            projected, valid = cached
        if return_validity:
            return projected, valid
        return projected

    def compute_training_loss_and_scores(
        self,
        train_pairs,
        dataset_state,
        return_score_matrix=False,
        compute_loss=True,
    ):
        del dataset_state
        if self.uses_precomputed_score():
            # This matrix only covers dev_pairs. Using its diagonal during decision-fusion
            # training would leak evaluation labels.
            return None, None, None

        left_embeddings, left_valid = self.encode_entity_ids(
            train_pairs[:, 0],
            return_validity=True,
        )
        right_embeddings, right_valid = self.encode_entity_ids(
            train_pairs[:, 1],
            return_validity=True,
        )
        cosine_scores = torch.matmul(left_embeddings, right_embeddings.t())
        training_loss = None
        if compute_loss and self.supports_training():
            paired_valid = left_valid & right_valid
            if torch.any(paired_valid):
                valid_left = left_embeddings[paired_valid]
                valid_right = right_embeddings[paired_valid]
                logits = torch.matmul(valid_left, valid_right.t()) / self.temperature
                labels = torch.arange(logits.size(0), device=logits.device)
                loss_lr = F.cross_entropy(logits, labels)
                loss_rl = F.cross_entropy(logits.t(), labels)
                training_loss = 0.5 * (loss_lr + loss_rl)
            else:
                training_loss = self.projector[1].weight.sum() * 0.0

        if not return_score_matrix:
            return training_loss, None, None
        score_tensor = cosine_scores.clamp(-1.0, 1.0)
        validity_mask = left_valid.unsqueeze(1) & right_valid.unsqueeze(0)
        score_tensor = score_tensor * validity_mask.to(score_tensor.dtype)
        return training_loss, score_tensor, validity_mask

    def compute_training_loss(self, train_pairs, dataset_state):
        training_loss, _, _ = self.compute_training_loss_and_scores(
            train_pairs=train_pairs,
            dataset_state=dataset_state,
            return_score_matrix=False,
            compute_loss=True,
        )
        return training_loss

    @torch.no_grad()
    def get_score_tensor(
        self,
        row_indices=None,
        col_indices=None,
        device=None,
        return_validity=False,
    ):
        if self.uses_precomputed_score():
            score_tensor = self.precomputed_score_tensor
            if row_indices is not None:
                score_tensor = score_tensor[row_indices]
            if col_indices is not None:
                score_tensor = score_tensor[:, col_indices]
            if device is not None:
                score_tensor = score_tensor.to(device)
            if return_validity:
                return score_tensor, torch.ones_like(score_tensor, dtype=torch.bool)
            return score_tensor

        source_entity_ids = self.eval_source_entity_ids
        target_entity_ids = self.eval_target_entity_ids

        if row_indices is not None:
            source_entity_ids = source_entity_ids[row_indices]
        if col_indices is not None:
            target_entity_ids = target_entity_ids[col_indices]

        left_embeddings, left_valid = self.encode_entity_ids(
            source_entity_ids,
            return_validity=True,
        )
        right_embeddings, right_valid = self.encode_entity_ids(
            target_entity_ids,
            return_validity=True,
        )
        score_tensor = torch.matmul(left_embeddings, right_embeddings.t())
        score_tensor = torch.clamp(score_tensor, min=-1.0, max=1.0)
        valid_score_mask = left_valid.unsqueeze(1) & right_valid.unsqueeze(0)
        score_tensor = score_tensor * valid_score_mask.to(score_tensor.dtype)

        if device is not None:
            score_tensor = score_tensor.to(device)
            valid_score_mask = valid_score_mask.to(device)
        if return_validity:
            return score_tensor, valid_score_mask
        return score_tensor
